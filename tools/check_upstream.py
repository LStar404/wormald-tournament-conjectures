"""Rerun the six upstream checks while preserving their historical QA files.

Each deterministic JSON record generated by a check must agree with the saved
record as data. Fresh stdout and return codes are saved separately; historical
review bytes are restored so their publication hashes remain reproducible.
"""
from datetime import datetime, timezone
from pathlib import Path
import json
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
QA = ROOT / "verification" / "qa"
SCRIPTS = [
    "verification/verify_wormald_hessian_spectral_bridge.py",
    "verification/verify_wormald_fixed_base_extremum.py",
    "verification/audit_publication_identities.py",
    "verification/audit_expansion_and_rounding.py",
    "tools/check_translation.py",
    "tools/check_package.py",
]


def main():
    baseline = {p: p.read_bytes() for p in QA.glob("*.json")}
    runs = []
    succeeded = False
    try:
        for script in SCRIPTS:
            p = subprocess.run([sys.executable, script], cwd=ROOT, capture_output=True,
                               encoding="utf-8", errors="replace")
            runs.append({"script": script, "exit_code": p.returncode,
                         "stdout": p.stdout.strip(), "stderr": p.stderr.strip()})
            if p.returncode:
                raise RuntimeError(script + " failed: " + p.stderr.strip())
            for path, old in baseline.items():
                new = path.read_bytes()
                if json.loads(new) != json.loads(old):
                    raise AssertionError((str(path), "Generated data differs from baseline"))
                path.write_bytes(old)
        succeeded = True
    finally:
        for path, old in baseline.items():
            path.write_bytes(old)
        record = {"result": "passed" if succeeded else "failed",
                  "checked_at_utc": datetime.now(timezone.utc).isoformat(),
                  "historical_qa_preserved": True,
                  "scope": "Finite exact computations, translation alignment and historical "
                           "publication bytes; not general theorem certification.",
                  "runs": runs}
        (ROOT / "verification" / "upstream-rerun.json").write_text(
            json.dumps(record, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"result": "passed", "checks": len(runs)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
